#!/usr/bin/env python3
"""
批次跑 main.py，為每個變異產生 HTML 報告並把結果寫回表格。

輸入可以是 xlsx 或 csv，變異來源二選一：
  1. 有 `input` 欄位（chr-pos-ref-alt 格式）→ 直接使用
  2. 沒有 `input` 欄位 → 由 --chrom-col/--pos-col/--ref-col/--alt-col 組出
     （預設 chr / position / ref / alt，符合 data/clinvar_latest.csv）

寫回的欄位分兩組。

Tissue Involvement Statistics 的 8 個計數（依 mention input variant 區分 × 4 個 tissue）：
  - mention_Cardiac / mention_Skeletal / mention_Both / mention_Not_Specified
  - no_mention_Cardiac / no_mention_Skeletal / no_mention_Both / no_mention_Not_Specified

報告層級的中介資料：
  - n_articles           報告裡的文獻數（0 表示 ClinVar 沒有引用文章）
  - inferred_disease     Track B 類比推理預測的疾病（沒有文獻時才會有）
  - inferred_tissue      Track B 預測的組織
  - inference_confidence Track B 的信心等級
  - report_file          實際解析的報告檔名（也當作「這列已完成」的標記）

特性：
  - 每跑完一個變異就立刻存檔，避免 SSH 中斷後遺失進度
  - 已經有結果的變異會跳過（--force 可強制重跑）
  - 若 outputs/ 下已有對應報告，直接解析、不重跑 main.py
  - Ctrl+C 會等本筆完成並儲存再退出

用法（conda 環境 gm4）：
  python batch_run_variants.py --input data/clinvar_latest.csv
"""

from __future__ import annotations

import argparse
import re
import signal
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

import pandas as pd
from bs4 import BeautifulSoup

PROJECT_ROOT = Path(__file__).parent.resolve()
DEFAULT_INPUT = PROJECT_ROOT / "HGMD_TTN_processed.xlsx"
OUTPUT_DIR = PROJECT_ROOT / "outputs"
MAIN_PY = PROJECT_ROOT / "main.py"

INPUT_COL = "input"

RESULT_COLS = [
    "mention_Cardiac",
    "mention_Skeletal",
    "mention_Both",
    "mention_Not_Specified",
    "no_mention_Cardiac",
    "no_mention_Skeletal",
    "no_mention_Both",
    "no_mention_Not_Specified",
]

INT_META_COLS = ["n_articles"]
STR_META_COLS = [
    "inferred_disease",
    "inferred_tissue",
    "inference_confidence",
    "report_file",
]
META_COLS = INT_META_COLS + STR_META_COLS

DONE_COL = "report_file"

TISSUE_LABEL_TO_KEY = {
    "Cardiac": "Cardiac",
    "Skeletal": "Skeletal",
    "Both": "Both",
    "Not Specified": "Not_Specified",
}

INFERENCE_LABEL_TO_COL = {
    "Predicted Disease (inference)": "inferred_disease",
    "Predicted Tissue": "inferred_tissue",
    "Confidence": "inference_confidence",
}

VARIANT_RE = re.compile(r"^\w+\-\d+\-[ACGT]+\-[ACGT]+$", re.IGNORECASE)

# main.py 產生報告時一定會寫出的 footer；當成「報告完整寫完」的判斷依據
REPORT_COMPLETE_MARKER = "Generated by TTN Variant AI Agent"

_stop_requested = False


def _signal_handler(signum, frame):  # noqa: ANN001
    global _stop_requested
    _stop_requested = True
    print("\n[!] 收到中斷信號，跑完目前這筆並儲存後就結束 (再按一次 Ctrl+C 強制離開)…",
          flush=True)
    signal.signal(signal.SIGINT, signal.default_int_handler)


def expected_model_tags() -> list[str]:
    """複製 main.py 決定報告檔名的規則，回傳偏好順序的 tag 清單。

    main.py: 只有在 clinical extraction 啟用且真的有抓到文獻時才用模型名，
    否則用 "no-llm"。ClinVar 大多數變異沒有引用文章，所以 "no-llm" 是常態，
    不能只認模型名那一種。
    """
    tags: list[str] = []
    try:
        from config import ENABLE_LOCAL_CLINICAL_EXTRACTION, LOCAL_LLM_MODEL

        if ENABLE_LOCAL_CLINICAL_EXTRACTION:
            model_name = str(LOCAL_LLM_MODEL)
            short = model_name.split("/")[-1] if "/" in model_name else model_name
            tags.append(short.replace(":", "-").replace(" ", "_"))
    except Exception as exc:  # noqa: BLE001
        print(f"[warn] 無法從 config 取得 LOCAL_LLM_MODEL（{exc}），只用 no-llm 比對",
              flush=True)
    tags.append("no-llm")
    return tags


def find_existing_report(variant_id: str, preferred_tags: list[str]) -> Optional[Path]:
    """找已存在的報告。

    優先用目前 config 會產生的 tag，其次 no-llm，最後才接受其他（舊模型）tag，
    同一優先級取最新修改的。
    """
    candidates = sorted(OUTPUT_DIR.glob(f"{variant_id}_*.html"))
    if not candidates:
        return None

    def rank(path: Path) -> tuple[int, float]:
        tag = path.stem[len(variant_id) + 1:]
        try:
            tier = preferred_tags.index(tag)
        except ValueError:
            tier = len(preferred_tags)
        return (tier, -path.stat().st_mtime)

    return min(candidates, key=rank)


def _parse_tissue_counts(soup: BeautifulSoup) -> dict:
    """從 Tissue Involvement Statistics 區塊取出 8 個計數。"""
    counts = {col: 0 for col in RESULT_COLS}

    for h4 in soup.find_all("h4"):
        title = h4.get_text(" ", strip=True)
        if title.startswith("Articles that directly mention the input variant"):
            prefix = "mention_"
        elif title.startswith("Articles that do NOT directly mention the input variant"):
            prefix = "no_mention_"
        else:
            continue

        container = h4.parent
        if container is None:
            continue

        no_articles_p = container.find(
            "p", string=lambda s: s and "No articles in this category" in s
        )
        if no_articles_p is not None:
            continue

        for card in container.select(".info-card"):
            label_el = card.select_one(".label")
            value_el = card.select_one(".value")
            if not label_el or not value_el:
                continue
            label = label_el.get_text(strip=True)
            if label not in TISSUE_LABEL_TO_KEY:
                continue
            m = re.match(r"\s*(\d+)", value_el.get_text(strip=True))
            if not m:
                continue
            counts[f"{prefix}{TISSUE_LABEL_TO_KEY[label]}"] = int(m.group(1))

    return counts


def _parse_inference(soup: BeautifulSoup) -> dict:
    """從 Mechanistic Inference 區塊取出預測疾病 / 組織 / 信心。"""
    out: dict[str, Optional[str]] = {col: None for col in INFERENCE_LABEL_TO_COL.values()}

    section = soup.select_one("section.inference-section")
    if section is None:
        return out

    for card in section.select(".inference-card"):
        label_el = card.select_one(".label")
        value_el = card.select_one(".value")
        if not label_el or not value_el:
            continue
        col = INFERENCE_LABEL_TO_COL.get(label_el.get_text(strip=True))
        if col:
            out[col] = value_el.get_text(" ", strip=True) or None

    return out


def parse_report(html_path: Path) -> Optional[dict]:
    """解析 HTML 報告。

    回傳 {**8 個計數, n_articles, inferred_*}；若報告看起來沒寫完（缺 footer）
    則回傳 None 代表要求重跑。

    注意：「沒有文獻」是正常結果，不是失敗。main.py 在 pubmed_results 為空時
    根本不會產生 Tissue Involvement Statistics 區塊，此時 8 個計數應記為 0，
    而不是判定報告不完整（舊版就是在這裡把 ClinVar 大多數變異誤判成失敗）。
    """
    try:
        html = html_path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        print(f"  [warn] 讀檔失敗 {html_path.name}: {exc}", flush=True)
        return None

    if REPORT_COMPLETE_MARKER not in html:
        return None

    soup = BeautifulSoup(html, "html.parser")

    result: dict = {}
    if "Tissue Involvement Statistics" in html:
        result.update(_parse_tissue_counts(soup))
    else:
        result.update({col: 0 for col in RESULT_COLS})

    n_articles = 0
    lit_h2 = soup.find("h2", string=re.compile(r"Literature Review"))
    if lit_h2 is not None:
        m = re.search(r"\((\d+)\s+articles?\)", lit_h2.get_text(" ", strip=True))
        if m:
            n_articles = int(m.group(1))
    result["n_articles"] = n_articles

    result.update(_parse_inference(soup))
    return result


def run_main_py(
    variant_id: str,
    timeout: Optional[int] = None,
    extra_args: Optional[list[str]] = None,
) -> bool:
    """執行 python main.py <variant>。回傳是否成功（return code 0）。"""
    cmd = [sys.executable, str(MAIN_PY), variant_id, *(extra_args or [])]
    print(f"  [run] {' '.join(cmd)}", flush=True)
    try:
        result = subprocess.run(
            cmd,
            cwd=str(PROJECT_ROOT),
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        print(f"  [error] {variant_id} 執行超時 ({timeout}s)", flush=True)
        return False
    except KeyboardInterrupt:
        raise
    except Exception as exc:  # noqa: BLE001
        print(f"  [error] {variant_id} 執行失敗: {exc}", flush=True)
        return False
    return result.returncode == 0


def read_table(path: Path) -> pd.DataFrame:
    if path.suffix.lower() in (".csv", ".tsv"):
        sep = "\t" if path.suffix.lower() == ".tsv" else ","
        return pd.read_csv(path, sep=sep)
    return pd.read_excel(path)


def save_table(df: pd.DataFrame, path: Path) -> None:
    """以暫存檔 + rename 方式安全儲存，避免寫到一半中斷造成損壞。"""
    tmp = path.with_suffix(path.suffix + ".tmp")
    if path.suffix.lower() in (".csv", ".tsv"):
        sep = "\t" if path.suffix.lower() == ".tsv" else ","
        df.to_csv(tmp, sep=sep, index=False)
    else:
        df.to_excel(tmp, index=False)
    tmp.replace(path)


def ensure_columns(df: pd.DataFrame) -> pd.DataFrame:
    """確保結果欄位存在，計數用 nullable Int64、文字用 object。"""
    for col in RESULT_COLS + INT_META_COLS:
        if col not in df.columns:
            df[col] = pd.NA
        df[col] = df[col].astype("Int64")
    for col in STR_META_COLS:
        if col not in df.columns:
            df[col] = pd.NA
        df[col] = df[col].astype("object")
    return df


def build_variant_ids(df: pd.DataFrame, args: argparse.Namespace) -> pd.Series:
    """取得每列的 chr-pos-ref-alt。有 input 欄就用它，否則從座標欄組出來。"""
    if INPUT_COL in df.columns:
        print(f"[info] 使用 '{INPUT_COL}' 欄位作為變異來源", flush=True)
        return df[INPUT_COL].astype(str).str.strip()

    cols = [args.chrom_col, args.pos_col, args.ref_col, args.alt_col]
    missing = [c for c in cols if c not in df.columns]
    if missing:
        raise SystemExit(
            f"[error] 表格既沒有 '{INPUT_COL}' 欄位，也缺少座標欄 {missing}；"
            f"現有欄位: {list(df.columns)}"
        )
    print(f"[info] 由 {' / '.join(cols)} 組出變異 ID", flush=True)

    def _fmt_pos(v) -> str:  # noqa: ANN001
        s = str(v).strip()
        return s[:-2] if s.endswith(".0") else s

    return (
        df[args.chrom_col].astype(str).str.strip().str.replace("^chr", "", regex=True)
        + "-"
        + df[args.pos_col].map(_fmt_pos)
        + "-"
        + df[args.ref_col].astype(str).str.strip().str.upper()
        + "-"
        + df[args.alt_col].astype(str).str.strip().str.upper()
    )


def row_is_done(row: pd.Series) -> bool:
    """已完成的判斷：有 report_file，或（舊表格）8 個計數都已填。"""
    marker = row.get(DONE_COL)
    if pd.notna(marker) and str(marker).strip():
        return True
    return all(pd.notna(row.get(c)) for c in RESULT_COLS)


def write_result(df: pd.DataFrame, idx: int, result: dict, report_name: str) -> None:
    for col in RESULT_COLS + INT_META_COLS:
        df.at[idx, col] = int(result.get(col) or 0)
    for col in STR_META_COLS:
        if col == DONE_COL:
            continue
        df.at[idx, col] = result.get(col)
    df.at[idx, DONE_COL] = report_name


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--input",
        type=Path,
        default=None,
        help=f"輸入表格，支援 .csv/.tsv/.xlsx (預設: {DEFAULT_INPUT.name})",
    )
    parser.add_argument(
        "--xlsx",
        type=Path,
        default=None,
        help="（舊參數，等同 --input）",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="結果輸出路徑 (預設: 輸入檔名加 _batch 後綴，避免覆蓋原始資料)",
    )
    parser.add_argument("--chrom-col", default="chr", help="染色體欄位名 (預設: chr)")
    parser.add_argument("--pos-col", default="position", help="GRCh38 位置欄位名 (預設: position)")
    parser.add_argument("--ref-col", default="ref", help="ref 欄位名 (預設: ref)")
    parser.add_argument("--alt-col", default="alt", help="alt 欄位名 (預設: alt)")
    parser.add_argument(
        "--start",
        type=int,
        default=0,
        help="從第幾列開始 (0-based, 不含表頭)",
    )
    parser.add_argument(
        "--end",
        type=int,
        default=None,
        help="跑到第幾列為止 (exclusive)",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="最多跑幾筆 (在 skip 後計算)",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=None,
        help="每筆 main.py 執行的逾時秒數 (預設不限)",
    )
    parser.add_argument(
        "--parse-only",
        action="store_true",
        help="只解析已存在的 HTML 報告，不跑 main.py（用來補回先前產生過的結果）",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="忽略既有結果，全部重跑",
    )
    parser.add_argument(
        "--variant",
        type=str,
        default=None,
        help="只跑單一變異 (例如 2-178527031-T-C)，會更新對應的列",
    )
    parser.add_argument(
        "--filter",
        action="append",
        default=[],
        metavar="COL=VAL1|VAL2",
        help=(
            "只處理指定欄位符合任一值的列，可重複使用。例如 "
            "--filter 'Germline classification=Pathogenic|Likely pathogenic'"
        ),
    )
    parser.add_argument(
        "--skip-evo2",
        action="store_true",
        help="轉傳給 main.py：跳過 Evo2（大幅加快批次速度）",
    )
    parser.add_argument(
        "--skip-clinical-extraction",
        action="store_true",
        help="轉傳給 main.py：跳過本地 LLM 擷取（Track B 會走 rule-based fallback）",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="只列出待處理的變異與既有報告狀態，不執行也不寫檔",
    )
    args = parser.parse_args()

    input_path: Path = (args.input or args.xlsx or DEFAULT_INPUT).resolve()
    if not input_path.exists():
        print(f"[error] 找不到輸入表格: {input_path}", file=sys.stderr)
        return 1
    if not MAIN_PY.exists():
        print(f"[error] 找不到 main.py: {MAIN_PY}", file=sys.stderr)
        return 1

    out_path: Path = (
        args.out.resolve()
        if args.out is not None
        else input_path.with_name(f"{input_path.stem}_batch{input_path.suffix}")
    )

    # 已有輸出檔就從它續跑，保留先前進度
    source_path = out_path if out_path.exists() and not args.force else input_path
    print(f"[info] 讀取 {source_path}", flush=True)
    df = read_table(source_path)
    print(f"[info] 結果將寫入 {out_path}", flush=True)

    variant_ids = build_variant_ids(df, args)
    df = ensure_columns(df)

    preferred_tags = expected_model_tags()
    print(f"[info] 報告 tag 偏好順序: {preferred_tags}", flush=True)

    extra_args: list[str] = []
    if args.skip_evo2:
        extra_args.append("--skip-evo2")
    if args.skip_clinical_extraction:
        extra_args.append("--skip-clinical-extraction")

    total_rows = len(df)
    start = max(0, args.start)
    end = total_rows if args.end is None else min(args.end, total_rows)
    indices = df.index[start:end].tolist()

    if args.variant is not None:
        target = args.variant.strip()
        match_idx = variant_ids.index[variant_ids == target].tolist()
        if not match_idx:
            print(f"[error] 在表格中找不到變異 {target}", file=sys.stderr)
            return 1
        indices = match_idx

    for spec in args.filter:
        if "=" not in spec:
            print(f"[error] --filter 格式應為 COL=VAL1|VAL2，收到 '{spec}'", file=sys.stderr)
            return 1
        col, _, raw_values = spec.partition("=")
        col = col.strip()
        if col not in df.columns:
            print(f"[error] --filter 欄位 '{col}' 不存在；現有欄位: {list(df.columns)}",
                  file=sys.stderr)
            return 1
        wanted = {v.strip() for v in raw_values.split("|") if v.strip()}
        keep = df[col].astype(str).str.strip().isin(wanted)
        indices = [i for i in indices if keep.at[i]]
        print(f"[info] --filter {col} in {sorted(wanted)} -> 剩下 {len(indices)} 列",
              flush=True)

    # 先過濾出真正要處理的列，讓進度顯示有意義
    todo: list[tuple[int, str]] = []
    skipped = 0
    invalid = 0
    for idx in indices:
        variant_id = str(variant_ids.at[idx]).strip()
        if not variant_id or variant_id.lower() == "nan":
            continue
        if not VARIANT_RE.match(variant_id):
            if invalid < 10:
                print(f"[skip] row {idx}: '{variant_id}' 不符合 chr-pos-ref-alt 格式",
                      flush=True)
            invalid += 1
            continue
        if not args.force and row_is_done(df.loc[idx]):
            skipped += 1
            continue
        todo.append((idx, variant_id))
        if args.limit is not None and len(todo) >= args.limit:
            break

    print(f"[info] 待處理 {len(todo)} 筆；已完成略過 {skipped} 筆；格式不符 {invalid} 筆",
          flush=True)

    if args.dry_run:
        have = 0
        for idx, variant_id in todo:
            report = find_existing_report(variant_id, preferred_tags)
            if report is not None:
                have += 1
            print(f"  row {idx}: {variant_id} -> "
                  f"{report.name if report else '(需要跑 main.py)'}", flush=True)
        print(f"\n[dry-run] 其中 {have} 筆已有報告可直接解析，"
              f"{len(todo) - have} 筆需要跑 main.py", flush=True)
        return 0

    if not todo:
        print("[info] 沒有要處理的列，結束", flush=True)
        save_table(df, out_path)
        return 0

    signal.signal(signal.SIGINT, _signal_handler)
    save_table(df, out_path)

    processed = 0
    parsed_existing = 0
    ran_main = 0
    failed = 0

    for n, (idx, variant_id) in enumerate(todo, 1):
        if _stop_requested:
            break

        print(f"\n[{n}/{len(todo)}] row {idx} variant = {variant_id}", flush=True)
        t0 = time.time()

        report_path = find_existing_report(variant_id, preferred_tags)
        result: Optional[dict] = None

        if report_path is not None and not args.force:
            print(f"  [reuse] 找到既有報告 {report_path.name}", flush=True)
            result = parse_report(report_path)
            if result is not None:
                parsed_existing += 1
            else:
                print("  [warn] 既有報告不完整（缺 footer），將重跑", flush=True)

        if result is None:
            if args.parse_only:
                print("  [skip] --parse-only 模式且沒有可用既有報告", flush=True)
                continue

            ok = run_main_py(variant_id, timeout=args.timeout, extra_args=extra_args)
            if not ok:
                failed += 1
                print(f"  [error] main.py 失敗，跳過 {variant_id}", flush=True)
                continue

            report_path = find_existing_report(variant_id, preferred_tags)
            if report_path is None:
                failed += 1
                print(f"  [error] main.py 跑完卻找不到 outputs/{variant_id}_*.html",
                      flush=True)
                continue

            result = parse_report(report_path)
            if result is None:
                failed += 1
                print(f"  [error] 解析新產生的報告失敗: {report_path.name}", flush=True)
                continue

            ran_main += 1

        write_result(df, idx, result, report_path.name)
        save_table(df, out_path)
        processed += 1

        dt = time.time() - t0
        tissue_summary = ", ".join(
            f"{c.replace('no_mention_', 'N:').replace('mention_', 'M:')}={result[c]}"
            for c in RESULT_COLS
        )
        detail = f"articles={result['n_articles']}, {tissue_summary}"
        if result.get("inferred_disease"):
            detail += (f" | inference: {result['inferred_disease']}"
                       f" / {result.get('inferred_tissue')}"
                       f" ({result.get('inference_confidence')})")
        print(f"  [ok] {variant_id} 完成 ({dt:.1f}s) -> {detail}", flush=True)

    print("\n========== 完成 ==========", flush=True)
    print(f"已處理: {processed} 筆", flush=True)
    print(f"  - 解析既有報告: {parsed_existing}", flush=True)
